/* *
 * 중국 본토의 일광 절약 시간 결정 - 주류 배반 구경과 단어별로 정렬됩니다.
 *
 *원인: 사용자 메시지(2026-08-13) "중국 본토는 1986년부터 1992년까지 일광 절약 시간제를 시행했습니다. 이 소프트웨어가 이를 설명할 수 있을지 궁금합니다."
 * 당시의 대답은 "아니요"였습니다. lib/ziwei/true-solar-time.ts의 구경은 "동팔구 시계 시간 + 경도 보정 + 평균 시차"뿐이었습니다.
 * 일광 절약 시간 처리는 전체 사이트에서 찾을 수 없으며 양식에 프롬프트도 없습니다.
 *
 * 이것이 중요한 이유: 일광 절약 시간 동안 시계는 1시간 앞으로 이동하고 시진은 2시간 단위로 이동합니다 ——
 * 출생시간이 시진 경계에 해당하는 사람의 경우 명궁/신궁/대한이 완전히 대체됩니다. 경도 수정보다 훨씬 더 심각합니다(최대 17분).
 *
 * ── 데이터 소스 및 구경 ──────────────────────────────────────────
 * 테이블 및 판단 로직은 대중적인 표준**(XLS_CN 테이블 및 해당 판단 기능)에 따라 구성되며 최적 표준 디스크로 검증됩니다.
 * 이 창고의 철칙은 "배반는 주류 배반 구경과 일치해야 합니다"이므로 복사하고 내 자신의 이해에 따라 변경하지 않습니다.
 *
 * IANA tzdata(아시아/상하이)(2026-08-24, Node ICU를 사용한 일일 샘플링)와 비교:
 * · 1986/1987/1989/1990/1991 시작일은 **정확히 동일**합니다.
 * · 주류 종료 날짜는 항상 IANA "마지막 하루"보다 1일 늦습니다. 이는 데이터 차이가 아니라 의미상의 차이입니다.
 * IANA는 종료일 02:00에 전환하며 주류 표준에서는 전체 전환일을 일광 절약 시간제로 계산합니다.
 * · **1988년의 시작일은 실제 불일치입니다**: 주류 구경 4/10, IANA 4/17(두 날 모두 일요일). 철의 법칙에 따라 주류 구경을 선택하십시오.
 * · 1979년 이전에는 큰 차이가 있었습니다. IANA의 아시아/상하이에는 전쟁 기간과 중화인민공화국 건국 초기에 대한 기록이 흩어져 있습니다.
 * (대부분의 연도는 일광 절약 시간이 없는 것으로 기록됩니다.) 주류 구경은 단순화된 국가 표를 사용합니다. 철법에 따른 주류 구경도 채용.
 *
 * ──1시간을 자동으로 줄이지 않고 프롬프트만 표시하는 이유 ────────────────────────────
 * 주류 배반 소프트웨어 자체는 팝업 알림일 뿐입니다(일광 절약 시간으로 판단되면 설명 텍스트 단락을 표시하고,
 *전체 여정에 1시간 단축은 없습니다.) 이 디자인은 정확합니다:
 * **사용자가 일광 절약 시간제 판독값을 보고하고 있는지 아니면 자신이 변환한 표준 시간을 보고하고 있는지 알 수 있는 방법이 없습니다. **
 * 조용히 1시간을 빼면 계산 착오가 발생할 수 있을 뿐만 아니라 기존 내역 명반이 모두 자동으로 변경될 수 있습니다. 그러니 알리고 사용자가 스스로 결정하도록 하세요.
 * 2026-09-30 웹마스터는 다음과 같이 동의합니다. 와이드스크린 컴퓨터의 일광 절약 시간 설명 오버레이에 "07:30까지 1시간 빼기" 버튼을 추가합니다. -
 * 여전히 **사용자 자신의 클릭**이며 클릭을 취소할 수 있으며 자동으로 줄어들지 않습니다(comComponents/heming/HemingStepForm.tsx). */

/* * 공통 구경 XLS_CN, 문자 그대로 복사: [연도, 시작 월, 시작일, 종료 월, 종료일], 시작 및 종료일 ** 둘 다 **를 포함합니다. */
const XLS_CN: readonly (readonly [number, number, number, number, number])[] = [
  [1935, 5, 1, 9, 30], [1936, 5, 1, 9, 30], [1937, 5, 1, 9, 30], [1938, 5, 1, 9, 30],
  [1939, 5, 1, 9, 30], [1940, 5, 1, 9, 30], [1941, 5, 1, 9, 30], [1942, 5, 1, 9, 30],
  [1943, 5, 1, 9, 30], [1944, 5, 1, 9, 30], [1945, 5, 1, 9, 30], [1946, 5, 1, 9, 30],
  [1947, 5, 1, 9, 30], [1948, 5, 1, 9, 30], [1949, 5, 1, 9, 30], [1950, 5, 1, 9, 30],
  [1951, 5, 1, 9, 30], [1952, 3, 1, 10, 31], [1953, 4, 1, 10, 31], [1954, 4, 1, 10, 31],
  [1955, 5, 1, 9, 30], [1956, 5, 1, 9, 30], [1957, 4, 1, 9, 30], [1958, 4, 1, 9, 30],
  [1959, 4, 1, 9, 30], [1960, 6, 1, 9, 30], [1961, 6, 1, 9, 30], [1974, 4, 1, 10, 31],
  [1975, 4, 1, 10, 31], [1979, 7, 1, 9, 30], [1986, 5, 4, 9, 14], [1987, 4, 12, 9, 13],
  [1988, 4, 10, 9, 11], [1989, 4, 16, 9, 17], [1990, 4, 15, 9, 16], [1991, 4, 14, 9, 15],
] as const;

/* *
 * 양력 날짜가 중국 본토의 일광 절약 시간제인지 여부.
 *
 * ★ 판단 논리는 공통 표준에 따라 단어별로 정렬됩니다(문서 헤더의 참고 참조): **순전히 날짜를 기준으로**, 시간을 보지 않습니다.
 *원래 형태:
 * (월 > m1 && 월 < m2)인 경우 true를 반환합니다.
 * if (월 == m1) { if (일 >= d1) return true; }
 * else if (월 == m2) { if (일 <= d2) return true; }
 * 참고 `else if` - 월 == m1이고 일 < d1인 경우 m2 분기는 더 이상 비교되지 않습니다. 이는 일반적인 표준과 일치합니다. "쉽게 최적화"하지 마십시오. */
export function isChinaDST(year: number, month: number, day: number): boolean {
  for (const [y, m1, d1, m2, d2] of XLS_CN) {
    if (year !== y) continue;
    if (month > m1 && month < m2) return true;
    if (month === m1) {
      if (day >= d1) return true;
    } else if (month === m2) {
      if (day <= d2) return true;
    }
  }
  return false;
}

/* * 해당 연도가 일광 절약 시간제 적용 여부(연도 선택 시 주문이 완료될 때까지 기다리지 않고 사용자에게 미리 알리는 형태로 사용됨). */
export function isChinaDSTYear(year: number): boolean {
  return XLS_CN.some(([y]) => y === year);
}

/* * 올해의 일광 절약 시간 간격(카피라이팅 표시용). 테이블 돌아가기 null에는 없습니다. */
export function chinaDSTRange(year: number): { start: string; end: string } | null {
  const hit = XLS_CN.find(([y]) => y === year);
  if (!hit) return null;
  const [, m1, d1, m2, d2] = hit;
  return { start: `${m1}월 ${d1}일`, end: `${m2}월 ${d2}일` };
}

/* * 연중 일광 절약 시간의 시작과 끝(숫자, 영어 및 기타 언어의 경우 월과 일을 직접 표기할 수 있으며 시작과 끝이 모두 포함됨). 테이블 돌아가기 null에는 없습니다. */
export function chinaDSTSpan(year: number): { startMonth: number; startDay: number; endMonth: number; endDay: number } | null {
  const hit = XLS_CN.find(([y]) => y === year);
  if (!hit) return null;
  const [, startMonth, startDay, endMonth, endDay] = hit;
  return { startMonth, startDay, endMonth, endDay };
}

/* * 카피라이팅 및 회귀용으로 표에 포함된 모든 연도(오름차순). */
export function chinaDSTYears(): number[] {
  return XLS_CN.map(([y]) => y);
}
