/* *
 * 별의 밝기를 확인하세요. 돌아가기 중국어 밝기 문자 또는 정의되지 않음(별은 포함되지 않음/기본 구경은 공백 0으로 남음)
 * ★ 기본 학교='QS'(Quanshu School): 주류 배반 소프트웨어 "성요 Brightness"에는 기본적으로 "Dou Shu Quanshu 기반"이 선택되어 있습니다(설정 페이지 증거).
 * 인덱스: SB 테이블 "하위는 1부터 시작"(하위 = 열 1...hai = 열 12), BranchIdx 하위는 0부터 시작하므로 col = BranchIdx + 1.
 * 경험적 증거: SB_QS + BRIGHTNESS_NUM_TO_CN + Ziqiyi, 표준 디스크는 19/19(10 주성 + 5 보조성 + 4 살성)에 나타납니다.
 * @param BranchIdx 별이 위치한 궁은 지지 이고 자식은 0 부터 시작합니다 (child=0...hai=11) */
export function schoolStarBrightness(
  starName: string,
  branchIdx: number,
  school: BrightnessSchool = 'QS',
): string | undefined {
  const id = SCHOOL_NAME_TO_ID[starName];
  if (id == null) return undefined;
  const v = SB_BY_SCHOOL[school]?.[id]?.[branchIdx + 1]; // 쯔치이
  if (v == null || v === 0) return undefined;            // 0 = 기본 구경은 공백으로 남겨져 표시되지 않습니다.
  return BRIGHTNESS_NUM_TO_CN_BY_SCHOOL[school][v];       // 장르에 따라 매핑 선택: QS/XD1=7레벨, ZZ/XD2=5레벨
}

