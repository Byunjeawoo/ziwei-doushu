// ★ 2026-06-20 전체 세트는 주류 배반 구경과 일치합니다. 이전 기본값은 주성에 손으로 두드린 희귀 도서 테이블을 사용하고 보조성에 XD1을 사용하는 것이었지만 표준과 일치하지 않았습니다.
